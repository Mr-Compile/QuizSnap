import 'imported_text_reconstructor.dart';

/// Normalizes and reconstructs raw text so it can be displayed or sent to the
/// AI prompt pipeline without isolated single-character lines, repeated
/// headers/footers, or excessive noise.
class TextNormalizationService {
  static const int _defaultMaxPromptChars = 12000;

  /// Reconstructs and normalizes text for both display and AI consumption.
  static String reconstruct(String rawText) {
    final reconstructed = ImportedTextReconstructor.reconstruct(rawText);
    return _removeNoise(reconstructed);
  }

  /// Cleans text for use as an AI prompt.
  static String cleanForPrompt(String rawText, {int maxChars = _defaultMaxPromptChars}) {
    String cleaned = reconstruct(rawText);

    // 1. Drop lines that are only a single character (often OCR artifacts).
    final lines = cleaned.split('\n');
    final kept = <String>[];
    for (final line in lines) {
      final trimmed = line.trim();
      if (trimmed.length <= 1 && !RegExp(r'^[\d•\-*]$').hasMatch(trimmed)) {
        continue;
      }
      kept.add(line);
    }
    cleaned = kept.join('\n');

    // 2. Remove repeated headers/footers/filler.
    cleaned = _removeRepeatedHeaders(cleaned);

    // 3. Collapse excessive blank lines.
    cleaned = cleaned.replaceAll(RegExp(r'\n{3,}'), '\n\n');

    // 4. Trim trailing/leading whitespace per line.
    cleaned = cleaned
        .split('\n')
        .map((l) => l.trim())
        .join('\n')
        .trim();

    // 5. Limit size while preserving sentence boundaries.
    return _truncateAtBoundary(cleaned, maxChars);
  }

  /// Cleans for on-screen display; less aggressive than prompt cleaning.
  static String cleanForDisplay(String rawText) {
    return _removeNoise(reconstruct(rawText));
  }

  /// Stores the raw extracted text plus the cleaned version.
  static ({String raw, String cleaned}) prepareBoth(String rawText) {
    final cleaned = cleanForDisplay(rawText);
    return (raw: rawText, cleaned: cleaned);
  }

  static String _removeNoise(String text) {
    return text
        .replaceAllMapped(RegExp(r'[ \t]+'), (_) => ' ')
        .replaceAll(RegExp(r'\n{3,}'), '\n\n')
        .trim();
  }

  static String _removeRepeatedHeaders(String text) {
    final lines = text.split('\n');
    final seen = <String, int>{};
    final result = <String>[];

    for (final line in lines) {
      final normalized = line.trim().toLowerCase();
      if (normalized.isEmpty) {
        result.add(line);
        continue;
      }
      // Treat short repeated non-content lines (likely page numbers / headers).
      if (normalized.length < 50 &&
          (RegExp(r'^(page\s*\d+|\d+\s*/\s*\d+|©|\d{4}|confidential|draft)$')
                  .hasMatch(normalized) ||
              RegExp(r'^(quizsnap|generated by|powered by)').hasMatch(normalized))) {
        if ((seen[normalized] ?? 0) >= 1) continue;
        seen[normalized] = (seen[normalized] ?? 0) + 1;
        result.add(line);
        continue;
      }

      seen[normalized] = (seen[normalized] ?? 0) + 1;
      if (seen[normalized]! > 2) continue; // repeated content
      result.add(line);
    }

    return result.join('\n').replaceAll(RegExp(r'\n{3,}'), '\n\n').trim();
  }

  static String _truncateAtBoundary(String text, int maxChars) {
    if (text.length <= maxChars) return text;

    final end = text.lastIndexOf(RegExp(r'[.!?\n]'), maxChars);
    if (end > maxChars * 0.8) {
      return text.substring(0, end + 1).trim();
    }
    return text.substring(0, maxChars).trim();
  }
}
